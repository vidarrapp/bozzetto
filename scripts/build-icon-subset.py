#!/usr/bin/env python3
"""Regenerate the icon subset (docs/development.md, "Icons").

The app uses about two dozen of the 3,500 glyphs in Flaticon's UIcons font
(solid, straight). This script reads the npm package
@flaticon/flaticon-uicons, finds every `fi-ss-*` class the source names,
and writes
  src/assets/icons/uicons-subset.woff2   the font with only those glyphs
  src/assets/icons/uicons-subset.css     the same CSS as the package's
                                         solid/straight.css for them
The two files are committed; the build never runs this (it needs Python
and `python3 -m pip install fonttools brotli`). Run it after adding or
removing an icon, then commit the result:

  python3 scripts/build-icon-subset.py          # write
  python3 scripts/build-icon-subset.py --check  # fail if the files are stale

The glyph outlines, the codepoints, the font's metrics and the base rules
(font-family, line-height, smoothing) are the package's own, so an icon
sits exactly where it did.
"""
import io
import re
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "node_modules" / "@flaticon" / "flaticon-uicons"
SOURCE_CSS = PACKAGE / "css" / "solid" / "straight.css"
OUT_DIR = ROOT / "src" / "assets" / "icons"
OUT_FONT = OUT_DIR / "uicons-subset.woff2"
OUT_CSS = OUT_DIR / "uicons-subset.css"
# Where icon classes are named: the app, and its pages (never node_modules, never the generated CSS).
SCAN = [ROOT / "src", ROOT / "index.html", ROOT / "admin", ROOT / "create", ROOT / "public" / "legal"]
SCAN_SUFFIXES = {".ts", ".css", ".html", ".svg", ".md"}
NAME = re.compile(r"\bfi-ss-([a-z0-9]+(?:-[a-z0-9]+)*)")


def used_icons() -> list[str]:
    names: set[str] = set()
    for base in SCAN:
        files = [base] if base.is_file() else [p for p in base.rglob("*") if p.is_file()]
        for path in files:
            if path.suffix not in SCAN_SUFFIXES or OUT_DIR in path.parents:
                continue
            names.update(NAME.findall(path.read_text(encoding="utf-8", errors="ignore")))
    return sorted(names)


def package_codepoints() -> dict[str, int]:
    css = SOURCE_CSS.read_text(encoding="utf-8")
    return {m.group(1): int(m.group(2), 16) for m in re.finditer(r"\.fi-ss-([a-z0-9-]+):before\{content:\"\\([0-9a-f]+)\"\}", css)}


def package_font() -> Path:
    css = SOURCE_CSS.read_text(encoding="utf-8")
    m = re.search(r"url\(\.\./(uicons-solid-straight-[A-Z0-9]+\.woff2)\)", css)
    if not m:
        sys.exit("no woff2 in the package's straight.css")
    return PACKAGE / "css" / m.group(1)


def build_font(codepoints: list[int]) -> bytes:
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = []  # no ligatures or variants: the page asks for a codepoint
    options.glyph_names = False
    options.notdef_outline = True
    options.name_IDs = [1, 2]
    options.drop_tables += ["GSUB", "GPOS", "GDEF"]
    font = TTFont(str(package_font()), recalcBBoxes=False, recalcTimestamp=False)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    out = io.BytesIO()
    font.flavor = "woff2"
    font.save(out)
    # The subsetter clears head.flags bit 1 (left side bearing at x=0), which the
    # package's font sets; put the package's flags back so no rasterizer reads
    # the glyphs any differently. The outlines and advances are already identical.
    out.seek(0)
    again = TTFont(out, recalcBBoxes=False, recalcTimestamp=False)
    again["head"].flags = TTFont(str(package_font()), lazy=True)["head"].flags
    final = io.BytesIO()
    again.flavor = "woff2"
    again.save(final)
    return final.getvalue()


def build_css(names: list[str], points: dict[str, int]) -> str:
    # The package's own @font-face (swap) and base rule, with the one file.
    head = (
        "/* Uicons by Flaticon (solid, straight), 3.3.1: only the glyphs the app uses.\n"
        " * Generated by scripts/build-icon-subset.py from @flaticon/flaticon-uicons;\n"
        " * do not edit. Flaticon License, free with attribution (THIRD_PARTY_NOTICES.md). */\n"
        "@font-face{font-family:uicons-solid-straight;src:url(./uicons-subset.woff2) format(\"woff2\");font-display:swap}\n"
        "i[class^=fi-ss-]:before,i[class*=\" fi-ss-\"]:before,span[class^=fi-ss-]:before,span[class*=fi-ss-]:before"
        "{font-family:uicons-solid-straight!important;font-style:normal;font-weight:400!important;font-variant:normal;"
        "text-transform:none;line-height:1;-webkit-font-smoothing:antialiased;-moz-osx-font-smoothing:grayscale}\n"
    )
    rules = "".join(f'.fi-ss-{n}:before{{content:"\\{points[n]:x}"}}\n' for n in names)
    return head + rules


def main() -> None:
    names = used_icons()
    points = package_codepoints()
    missing = [n for n in names if n not in points]
    if missing:
        sys.exit("not in the UIcons solid straight set: " + ", ".join(f"fi-ss-{n}" for n in missing))
    css = build_css(names, points)
    font = build_font([points[n] for n in names])
    if "--check" in sys.argv:
        stale = not OUT_CSS.exists() or OUT_CSS.read_text(encoding="utf-8") != css
        if stale:
            sys.exit("src/assets/icons/uicons-subset.css is stale: run scripts/build-icon-subset.py")
        print(f"icon subset is current: {len(names)} icons")
        return
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    OUT_FONT.write_bytes(font)
    OUT_CSS.write_text(css, encoding="utf-8")
    print(f"{len(names)} icons: {OUT_FONT.name} {len(font)} bytes, {OUT_CSS.name} {len(css)} bytes")


if __name__ == "__main__":
    main()
